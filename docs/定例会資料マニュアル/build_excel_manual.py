def main():
    wb = Workbook()
    ws = wb.active
    ws.title = "定例会資料の作り方"
    ws.sheet_view.showGridLines = False
    ws.column_dimensions["A"].width = 2
    for col in "BCDEF":
        ws.column_dimensions[col].width = 22
    MAINCOL = 2  # B

    r = 1
    def merge_write(row, text, font, fill=None, align=None, span=5, height=None):
        c = ws.cell(row=row, column=MAINCOL, value=text)
        c.font = font
        if fill: c.fill = fill
        c.alignment = align or Alignment(wrap_text=True, vertical="top")
        ws.merge_cells(start_row=row, start_column=MAINCOL, end_row=row, end_column=MAINCOL+span-1)
        if height: ws.row_dimensions[row].height = height
        return c

    for block in CONTENT:
        kind = block[0]
        if kind == "h1":
            r += 1
            merge_write(r, block[1], Font(bold=True, size=15, color=C_H1_FG),
                        PatternFill("solid", fgColor=C_H1_BG),
                        Alignment(wrap_text=True, vertical="center"), height=30)
            r += 2
        elif kind == "h2":
            merge_write(r, block[1], Font(bold=True, size=12, color=C_H2_FG),
                        PatternFill("solid", fgColor=C_H2_BG),
                        Alignment(wrap_text=True, vertical="center"), height=22)
            r += 2
        elif kind == "p":
            merge_write(r, block[1], Font(size=11))
            r += 1
        elif kind == "note":
            merge_write(r, block[1], Font(size=11),
                        PatternFill("solid", fgColor=C_NOTE))
            r += 1
        elif kind == "code":
            merge_write(r, block[1], Font(size=11, name="Consolas"),
                        PatternFill("solid", fgColor=C_CODE))
            r += 1
        elif kind == "table":
            header = block[1]; rows = block[2:]
            ncol = len(header)
            for j, h in enumerate(header):
                c = ws.cell(row=r, column=MAINCOL+j, value=h)
                c.font = Font(bold=True, color=C_H1_FG, size=10)
                c.fill = PatternFill("solid", fgColor=C_H2_BG.replace("D6E4F0","4472C4"))
                c.alignment = Alignment(wrap_text=True, vertical="center")
                c.border = Border(left=THIN,right=THIN,top=THIN,bottom=THIN)
            r += 1
            for row_vals in rows:
                for j, v in enumerate(row_vals):
                    c = ws.cell(row=r, column=MAINCOL+j, value=v)
                    c.font = Font(size=10)
                    c.alignment = Alignment(wrap_text=True, vertical="top")
                    c.border = Border(left=THIN,right=THIN,top=THIN,bottom=THIN)
                r += 1
            r += 1
        elif kind == "img":
            fname, caption = block[1], block[2]
            path = os.path.join(IMG, fname)
            with PILImage.open(path) as im:
                ow, oh = im.size
            disp_w = IMG_W
            disp_h = int(oh * (IMG_W / ow))
            xi = XLImage(path)
            xi.width = disp_w; xi.height = disp_h
            anchor = f"{get_column_letter(MAINCOL)}{r}"
            ws.add_image(xi, anchor)
            rows_span = math.ceil(disp_h / 20) + 1
            r += rows_span
            # caption
            merge_write(r, f"図：{caption}", Font(size=9, italic=True, color=C_CAP))
            r += 2

    wb.save(OUT)
    print("[OK]", OUT)


